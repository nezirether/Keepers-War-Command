"""Validate Phoenix designer exports and generate the public Lua art registry."""
import argparse
import json
import re
import struct
from functools import lru_cache
from pathlib import Path

from art_contract import SLOTS as PRODUCTION_SLOTS, catalog_ids, export_path, focal

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = "docs/PHOENIX_ART.json"
REGISTRY = "KeepersWarCommand/UI/ThemeArt.lua"
MEDIA = "KeepersWarCommand/Media/"
IDS = ("trogdor", "horde", "alliance", "blood-moon")
SLOTS = {
    "banner": (512, 256, 0.78), "header": (512, 64, 0.55),
    "crest": (128, 128, 1), "thumbnail": (256, 128, 1),
    "alert": (512, 128, 0.22), "ornament": (64, 64, 0.82),
}
FALLBACK = {
    "banner": "surface", "header": "header", "crest": "Emblem.tga",
    "thumbnail": "palette", "alert": "surface", "ornament": "surface",
}
REUSE = {"thumbnail": "banner", "alert": "header"}


def validate(read, manifest, catalog, themes):
    @lru_cache(maxsize=None)
    def texture(path, size=None, alpha=None, meaningful=True):
        if not re.fullmatch(r"(?:(?:Themes|Art/[a-z0-9-]+)/)?[A-Za-z0-9_-]+\.tga", path):
            raise ValueError(f"Invalid media-relative TGA path: {path}")
        data = read(MEDIA + path)
        if len(data) < 18:
            raise ValueError(f"{path}: truncated TGA header")
        ident, color_map, mode, _, _, _, _, _, width, height, bits, flags = struct.unpack(
            "<BBBHHBHHHHBB", data[:18]
        )
        if (color_map or mode != 2 or bits not in (24, 32) or not width or not height
                or flags & 0xC0 or (bits == 32 and flags & 15 != 8)
                or len(data) < 18 + ident + width * height * (bits // 8)):
            raise ValueError(f"{path}: unreadable uncompressed RGB/RGBA TGA")
        if size and (width, height) != tuple(size):
            raise ValueError(f"{path}: expected {size[0]}×{size[1]}, found {width}×{height}")
        if alpha is True and bits != 32:
            raise ValueError(f"{path}: missing alpha channel")
        if alpha is False and bits != 24:
            raise ValueError(f"{path}: expected RGB export")
        if alpha is True and meaningful:
            channel = data[21 + ident:18 + ident + width * height * 4:4]
            if min(channel) == 255 or max(channel) == 0:
                raise ValueError(f"{path}: expected meaningful transparency")

    if manifest["schema"] != 1 or set(manifest["skins"]) != set(IDS):
        raise ValueError("Expected the four approved flagship IDs and schema 1")
    lines = ["-- Generated by python tools/theme_art.py --write. Edit docs/PHOENIX_ART.json.",
             "KWC.ThemeArtwork={"]
    texture("Emblem.tga")
    for asset in set(re.findall(r"\{'([A-Z][A-Za-z]+)'\s*,\s*0?\.", themes)):
        texture(asset + ".tga")
    recipes = re.findall(r"\{'[^']+','[0-9A-F]{6}','[0-9A-F]{6}','[0-9A-F]{6}','[0-9A-F]{6}','([a-z]+)','([a-z]+)'", catalog)
    if len(recipes) != 100:
        raise ValueError("Expected 100 public catalog recipes")
    for motif, trim in recipes:
        texture("Themes/M_" + motif + ".tga", (256, 64))
        texture("Themes/T_" + trim + ".tga", (256, 32))
    for skin in IDS:
        pack = manifest["skins"][skin]
        if set(pack) != set(SLOTS):
            raise ValueError(f"{skin}: missing or unknown slots")
        lines.append(f" ['{skin}']={{")
        for slot, (width, height, opacity) in SLOTS.items():
            entry = pack[slot]
            if entry["fallback"] != FALLBACK[slot]:
                raise ValueError(f"{skin}/{slot}: expected fallback {FALLBACK[slot]}")
            if "reuse" in entry:
                source = REUSE.get(slot)
                if not source or entry["reuse"] != source or "reuse" in pack[source]:
                    raise ValueError(f"{skin}/{slot}: invalid reuse")
                artwork = pack[source]
            else:
                artwork = entry
                if entry["dimensions"] != [width, height]:
                    raise ValueError(f"{skin}/{slot}: invalid export dimensions")
                if not isinstance(entry["transparency"], bool) or (
                    slot in {"header", "crest", "alert", "ornament"} and not entry["transparency"]
                ):
                    raise ValueError(f"{skin}/{slot}: invalid transparency contract")
                for key in ("source", "license"):
                    if not isinstance(entry[key], str) or not entry[key].strip():
                        raise ValueError(f"{skin}/{slot}: missing {key}")
                texture(entry["path"], (width, height), entry["transparency"])
            x, y = artwork["focal"]
            if any(type(v) not in (int, float) or not 0 <= v <= 1 for v in (x, y)):
                raise ValueError(f"{skin}/{slot}: focal coordinates must be within [0, 1]")
            stem = artwork["path"][:-4].replace("/", "\\\\")
            aspect = artwork["dimensions"][0] / artwork["dimensions"][1]
            tint = "true" if slot == "ornament" and artwork["path"] == "SharedCorner.tga" else "false"
            crop = "nil" if slot in {"header", "alert"} else f"{aspect:g}"
            lines.append(f"  {slot}={{'{stem}',{opacity:g},{crop},{tint},{x:g},{y:g}}},")
        lines.append(" },")
    lines.extend(["}", ""])
    production = manifest.get("production", {})
    if not isinstance(production, dict):
        raise ValueError("production must be keyed by approved skin IDs")
    if production:
        valid_ids = set(catalog_ids(catalog))
        lines.append("KWC.ProductionThemeArtwork={")
        for skin in sorted(production):
            pack = production[skin]
            if skin not in valid_ids or pack.get("skin_id") != skin or pack.get("schema") != 1:
                raise ValueError(f"{skin}: invalid production identity")
            entries = pack["slots"]
            if set(entries) != set(PRODUCTION_SLOTS):
                raise ValueError(f"{skin}: expected all eight production slots")
            lines.append(f" ['{skin}']={{")
            for slot, (_, size, alpha, opacity, cover) in PRODUCTION_SLOTS.items():
                entry = entries[slot]
                for key in ("source", "license"):
                    if not isinstance(entry[key], str) or not entry[key].strip():
                        raise ValueError(f"{skin}/{slot}: missing {key}")
                path = export_path(skin, slot)
                x, y = focal(entry["focal"])
                texture(path, size, alpha, meaningful=slot in {"crest", "header", "alert", "ornament", "material", "trim"})
                stem = path[:-4].replace("/", chr(92) * 2)
                crop = f"{size[0] / size[1]:g}" if cover else "nil"
                runtime_slot = "banner" if slot == "dashboard" else slot
                lines.append(f"  {runtime_slot}={{'{stem}',{opacity:g},{crop},false,{x:g},{y:g}}},")
            lines.append(" },")
        lines.extend(["}", ""])
    return "\n".join(lines)


def check_inventory(paths, manifest):
    declared = {MEDIA + export_path(skin, slot)
                for skin in manifest.get("production", {}) for slot in PRODUCTION_SLOTS}
    found = {path for path in paths if path.casefold().startswith((MEDIA + "Art/").casefold())}
    extra, missing = sorted(found - declared), sorted(declared - found)
    if extra or missing:
        raise ValueError(f"Production artwork inventory mismatch. Unregistered: {extra}. Missing: {missing}.")


def check(read, write=False, paths=None):
    manifest = json.loads(read(MANIFEST))
    generated = validate(
        read, manifest,
        read("KeepersWarCommand/UI/ThemeCatalog.lua").decode(),
        read("KeepersWarCommand/UI/PublicThemes.lua").decode(),
    )
    if paths is not None:
        check_inventory(paths, manifest)
    if write:
        (ROOT / REGISTRY).write_text(generated, encoding="ascii", newline="\n")
    elif read(REGISTRY).decode().replace("\r\n", "\n") != generated:
        raise ValueError("Artwork registry is stale. Run python tools/theme_art.py --write.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="Regenerate ThemeArt.lua after validation")
    try:
        check(lambda path: (ROOT / path).read_bytes(), parser.parse_args().write)
    except (OSError, ValueError, KeyError, TypeError) as error:
        parser.exit(1, f"Theme art validation failed: {error}\n")
    print("Public theme artwork validated.")
